"""Convert a Scene into Asymptote source and PNG (PDF/SVG on request)."""

from __future__ import annotations

import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

from mathfig.geometry import (
    Arrow,
    Axis,
    Circle,
    Curve,
    Label,
    Line,
    Point,
    Primitive,
    Rectangle,
    Region,
    Style,
    Vec2,
    Vector,
)
from mathfig.scene import Scene


class AsymptoteNotFoundError(RuntimeError):
    """Raised when the `asy` executable is not on PATH."""


class AsymptoteError(RuntimeError):
    """Raised when Asymptote exits unsuccessfully."""


def fmt_num(x: float) -> str:
    rounded = round(x)
    if abs(x - rounded) < 1e-12:
        return str(int(rounded))
    return f"{x:.12g}"


def fmt_pair(xy: Vec2) -> str:
    return f"({fmt_num(xy[0])},{fmt_num(xy[1])})"


def latex_math(text: str) -> str:
    body = text.strip()
    if body.startswith("$") and body.endswith("$") and len(body) >= 2:
        return body
    return f"${body}$"


def _pen(style: Style, thickness: float | None = None, dashed: bool = False) -> str:
    thick = style.line_thickness_pt if thickness is None else thickness
    parts = [f"black+{fmt_num(thick)}pt"]
    if dashed:
        parts.append("dashed")
    return "+".join(parts)


def _join_path(points: tuple[Vec2, ...], *, closed: bool, smooth: bool) -> str:
    op = ".." if smooth else "--"
    body = op.join(fmt_pair(p) for p in points)
    if closed:
        return f"{body}{op}cycle"
    return body


def _emit_point(item: Point, style: Style) -> list[str]:
    if not item.draw:
        return []
    return [f"dot({fmt_pair(item.xy)}, {_pen(style)});"]


def _emit_line(item: Line, style: Style) -> list[str]:
    pen = _pen(style, item.thickness, item.dashed)
    return [f"draw({fmt_pair(item.start)}--{fmt_pair(item.end)}, {pen});"]


def _emit_arrow(item: Arrow, style: Style) -> list[str]:
    pen = _pen(style, item.thickness, item.dashed)
    return [
        f"draw({fmt_pair(item.start)}--{fmt_pair(item.end)}, {pen}, Arrow(SimpleHead));"
    ]


def _emit_curve(item: Curve, style: Style) -> list[str]:
    pen = _pen(style, dashed=item.dashed)
    path = _join_path(item.points, closed=item.closed, smooth=item.smooth)
    return [f"draw({path}, {pen});"]


def _emit_rectangle(item: Rectangle, style: Style) -> list[str]:
    if not item.draw:
        return []
    sw, _, ne, _ = item.vertices_ccw
    return [f"draw(box({fmt_pair(sw)}, {fmt_pair(ne)}), {_pen(style)});"]


def _emit_circle(item: Circle, style: Style) -> list[str]:
    pen = _pen(style, dashed=item.dashed)
    return [f"draw(circle({fmt_pair(item.center)}, {fmt_num(item.radius)}), {pen});"]


def _emit_region(item: Region, style: Style) -> list[str]:
    path = _join_path(item.vertices, closed=True, smooth=False)
    if item.hatch and style.hatch:
        return [f"fill({path}, pattern(\"hatch\"));"]
    return [f"fill({path}, white);"]


def _axis_anchor(item: Axis) -> str:
    dx = item.end[0] - item.start[0]
    dy = item.end[1] - item.start[1]
    if abs(dx) >= abs(dy):
        return "E" if dx >= 0 else "W"
    return "N" if dy >= 0 else "S"


def _emit_axis(item: Axis, style: Style) -> list[str]:
    lines = [
        f"draw({fmt_pair(item.start)}--{fmt_pair(item.end)}, {_pen(style)}, Arrow(SimpleHead));"
    ]
    if style.labels and item.label:
        lines.append(
            f"label(\"{latex_math(item.label)}\", {fmt_pair(item.end)}, {_axis_anchor(item)});"
        )
    return lines


def _emit_label(item: Label, style: Style) -> list[str]:
    if not style.labels:
        return []
    return [
        f"label(\"{latex_math(item.text)}\", {fmt_pair(item.xy)}, {item.anchor});"
    ]


def _vector_anchor(item: Vector) -> str:
    if item.label_anchor is not None:
        return item.label_anchor
    dx, dy = item.components
    if abs(dx) >= abs(dy):
        return "E" if dx >= 0 else "W"
    return "N" if dy >= 0 else "S"


def _emit_vector(item: Vector, style: Style) -> list[str]:
    lines = [
        f"draw({fmt_pair(item.origin)}--{fmt_pair(item.end)}, {_pen(style)}, Arrow(SimpleHead));"
    ]
    if style.labels and item.label:
        lines.append(
            f"label(\"{latex_math(item.label)}\", {fmt_pair(item.end)}, {_vector_anchor(item)});"
        )
    return lines


_EMITTERS: dict[type[Primitive], object] = {
    Point: _emit_point,
    Line: _emit_line,
    Arrow: _emit_arrow,
    Curve: _emit_curve,
    Rectangle: _emit_rectangle,
    Circle: _emit_circle,
    Region: _emit_region,
    Axis: _emit_axis,
    Label: _emit_label,
    Vector: _emit_vector,
}


def scene_to_asymptote(scene: Scene) -> str:
    style = scene.style
    lines = [
        "// Generated by mathfig. Do not edit by hand.",
        f"unitsize({fmt_num(style.unitsize_cm)}cm);",
        f"defaultpen(black+{fmt_num(style.line_thickness_pt)}pt);",
        "import patterns;",
        "",
        f'add("hatch", hatch(1.5mm, NW, false, black+0.25pt));',
        "",
    ]
    if not style.axes:
        items = [i for i in scene.items if not isinstance(i, Axis)]
    else:
        items = list(scene.items)
    for item in items:
        emitter = _EMITTERS[type(item)]
        lines.extend(emitter(item, style))  # type: ignore[operator]
    lines.append("")
    return "\n".join(lines)


@dataclass(frozen=True)
class RenderResult:
    asy: Path
    pdf: Path | None = None
    svg: Path | None = None
    png: Path | None = None


def write_asy(scene: Scene, path: Path | str) -> Path:
    asy_path = Path(path)
    asy_path.parent.mkdir(parents=True, exist_ok=True)
    asy_path.write_text(scene_to_asymptote(scene), encoding="utf-8")
    return asy_path


def _run_asy(asy_path: Path, fmt: str, dest_stem: Path) -> None:
    asy = shutil.which("asy")
    if asy is None:
        raise AsymptoteNotFoundError(
            "Asymptote (`asy`) was not found on PATH. "
            "Install Asymptote and a LaTeX engine to render PDF/SVG/PNG."
        )
    dest_stem.parent.mkdir(parents=True, exist_ok=True)
    cmd = [asy, "-f", fmt, "-o", str(dest_stem), str(asy_path)]
    try:
        completed = subprocess.run(
            cmd,
            check=False,
            capture_output=True,
            text=True,
        )
    except OSError as exc:
        raise AsymptoteError(f"failed to invoke asy: {exc}") from exc
    if completed.returncode != 0:
        detail = (completed.stderr or completed.stdout or "").strip()
        raise AsymptoteError(
            f"asy -f {fmt} failed with exit {completed.returncode}: {detail}"
        )


def render(
    scene: Scene,
    output: Path | str,
    *,
    png: bool = False,
    invoke: bool = True,
) -> RenderResult:
    """Write Asymptote source and the requested raster/vector outputs.

    Always writes ``.asy``. PNG is the default product: it is written when
    ``output`` ends in ``.png``, has no suffix, or ``png`` is true. PDF and
    SVG are written only when the output suffix is ``.pdf`` or ``.svg``.
    PNG rasterization uses Asymptote when ``asy`` is available, otherwise
    matplotlib.
    """
    output = Path(output)
    suffix = output.suffix.lower()
    if suffix == "":
        output = output.with_suffix(".png")
        suffix = ".png"
    stem = output.with_suffix("")
    asy_path = write_asy(scene, stem.with_suffix(".asy"))
    if not invoke:
        return RenderResult(asy=asy_path)

    want_png = png or suffix == ".png"
    want_pdf = suffix == ".pdf"
    want_svg = suffix == ".svg"

    pdf_path: Path | None = None
    svg_path: Path | None = None
    png_path: Path | None = None

    if want_pdf:
        _run_asy(asy_path, "pdf", stem)
        pdf_path = stem.with_suffix(".pdf")
    if want_svg:
        _run_asy(asy_path, "svg", stem)
        svg_path = stem.with_suffix(".svg")
    if want_png:
        png_path = _write_png(scene, asy_path, stem.with_suffix(".png"))

    return RenderResult(asy=asy_path, pdf=pdf_path, svg=svg_path, png=png_path)


def _write_png(scene: Scene, asy_path: Path, png_path: Path) -> Path:
    if shutil.which("asy") is not None:
        try:
            _run_asy(asy_path, "png", png_path.with_suffix(""))
            if png_path.is_file():
                return png_path
        except (AsymptoteNotFoundError, AsymptoteError):
            pass
    from mathfig.png_renderer import scene_to_png

    return scene_to_png(scene, png_path)
